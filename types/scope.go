package types

// Scope 事实卡的**记录级归属**。
//
// # 它与 Namespace 正交——两个不同的隔离维度
//
//   - Namespace（见 store.Namespace）：**整库级**隔离。一个库里的这一组记忆
//     互相可见，隔离的粒度是「库」。
//   - Scope（本类型）：**记录级**归属。同一个库里，「人人都该看到的全局事实」
//     与「某一组自己的环境事实」共处在一起，隔离的粒度是「一条卡」。
//
// # 为什么不能拿 Namespace 表达第二层
//
// 用 Namespace 表达「本组事实」，意味着「一条全局事实」得向每一个组复制一份：
// 写放大，且全局事实一旦新增就得回头补所有组的副本。
// 那是不可行的建模，不是配置问题。
//
// # 语义只有两条，别加第三种
//
//   - 空（零值）  ⇒ **全局可见**：任何读取方都看得见这张卡。
//   - 非空        ⇒ **仅同归属可见**：读取方的 Scope 与之相同才看得见。
//
// # 归属由宿主定义
//
// 本仓不枚举归属的种类（不认「客户/团队/项目」这类宿主概念），
// 只认一个不透明标识：**同标识可见，异标识不可见**。
// 语义归宿主，本仓只保证这条判据在两个后端上口径一致。
type Scope string

// IsGlobal 是否是全局归属（零值）。
func (s Scope) IsGlobal() bool { return s == "" }

// VisibleTo 这张卡对 reader 可见吗。
//
// 判据只有一条：**全局的谁都看得见，非全局的只有同归属看得见**。
//
// 这条判据在两处各有一份实现——存储层的 SQL 条件、召回层的后置兜底——
// 跨后端的一致性由 storage/parity 的共享断言钉住（见 tAtomScopeIsolation）。
func (s Scope) VisibleTo(reader Scope) bool {
	return s == "" || s == reader
}
