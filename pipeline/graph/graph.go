// Package graph 图谱投影与多跳检索：把关系型事实投影成边，再按跳数取回相关实体。
//
// # 边是派生物，事实卡才是真源
//
// 边从事实卡投影而来，投影丢了可以按事实卡重投影，事实卡丢了投影救不回来——
// 两者的地位不对称。故本包只提供「落边 / 清投影 / 多跳取」这套机制，
// **不判定任何关系是否成立**：关系成不成立是事实卡的事，宿主给声明，本包落成边。
//
// 本包**不认识任何领域**：关系名由宿主给，本仓不枚举关系词表，
// 也不认识边所指向的那些对象是什么——它只认识「实体之间有一条带强度的关系」。
//
// # 三条不可协商的纪律
//
//  1. **边必须有溯源。** 没有溯源的边是「没人敢删的垃圾」：事实卡被推翻后
//     清不掉它，图就开始说谎。故没有出处的边**不许落**（见 ErrMissingSource）。
//  2. **多跳必须按实体去重。** 关系图里必然有回路，不去重就会无限展开（见 traverse.go）。
//  3. **归属判定要在存储层之外再判一次。** 漏过滤的失效形态是**串户**而不是少取，
//     而串户在结果里长得与正常结果一模一样（见 traverse.go 的可见性复查）。
package graph

// MaxDepthLimit 跳数硬顶。
//
// 为什么是 4：再深的多跳既**不可解释**（人说不出「它经由什么到达」），
// 也**不可预算**（深度决定取数轮数与展开规模）。它是经验上限，不是数学上限——
// 真需要更深的链路时该重新设计这一层，而不是把闸门挪到 8。
const MaxDepthLimit = 4

// defaultMaxResults 结果条数缺省上限。
//
// 有上限不是因为多跳会炸（去重已经保证了），而是调用方要能预算：
// 一次多跳取回多少条，得由调用点看得见，而不是由图的形状决定。
const defaultMaxResults = 50
