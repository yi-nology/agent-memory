// Package evaluation 召回质量评测面：合成数据集 + 质量指标 + 可复现实验运行器。
//
// # 它补的是哪一块空缺
//
// 本仓此前的测试全是**行为断言**：该召回的召回了、不该召回的不召回。
// 那种断言能抓住「某条事实彻底召不回来」，却答不了「多召回出来的东西里
// 有多少是相关的」——于是排序、融合、查询理解的任何改动都只能靠感觉，
// 改完只能说「好像更准了」。
//
// 本包给的是**质量判据**：给定一份标注了「哪些事实算相关」的数据集，
// 算出一组可比较的指标（Recall@k / Precision@k / nDCG@k / MRR / HitRate）。
//
// # 它是判据面，不是产品面
//
// 本包不进任何召回链，也不被召回链依赖：它只**问**召回器问题、**记**答案。
// 方向永远是「评测 → 被评测」，反过来就成了「用指标调指标」。
//
// 被评测的召回器由调用方以窄接口注入（见 Retriever），故本包对召回实现
// **零耦合**：它不关心召回是词面的、语义的、还是宿主自造的，
// 只要求「给一条查询，返回一串有序的标识」。
//
// # 依赖方向
//
// 本包只依赖 types（事实卡与归属）。评测面不需要存储、不需要模型，
// 更不需要知道事实是怎么落库的——标注就是真源，库只是被评测对象的载体。
package evaluation

import "github.com/yi-nology/agent-memory/types"

// Case 一条评测用例。
//
// 一条用例 = 一次查询 + 关于「什么算相关」的标注。
// 标注是评测的**唯一真源**：指标只是标注的函数，
// 所以标注含糊时，指标再精确也只是精确地算错。
type Case struct {
	// ID 用例标识（逐用例明细按它回指）。
	ID string
	// Query 查询串。
	Query string
	// Scope 读者归属（空=不隔离）。
	//
	// 与 store.AtomFilter.Scope 同一套语义：空=不隔离，非空=只该归属可见。
	// 评测里带它，是为了让「归属隔离」也能被指标覆盖——
	// 越权召回在数据上完全看不出来（内容一条不少，只是多了不该看的），
	// 而它在精确率上会直接扣分。
	Scope types.Scope
	// Relevant 相关的事实卡 ID 集合（**相关**=应当被召回）。
	//
	// 空集合意味着「这条用例无从判分」：运行器会跳过它，
	// 它不进任何分母（见 run.go 的聚合口径）。
	Relevant []string
	// NonRelevant 明确不相关的 ID 集合（可选，用于算精确率）。
	//
	// 收录的是「看着像、其实不是」的干扰事实（含近义干扰与不可见事实）。
	// 注意本包的精确率口径是「命中数 / k」，不需要这张表；
	// 它的用处是**人看**：明细里能对照出「哪些是标注过的不相关」。
	NonRelevant []string
	// Entities 宿主给的实体提示（可选）。
	Entities []string
	// SessionID / ThreadID 可选。
	SessionID string
	ThreadID  string
}

// Dataset 一组用例。
type Dataset struct {
	// Name 数据集名（报告里回显，便于比对多份结果）。
	Name string
	// Cases 用例集（顺序即评测顺序）。
	//
	// 顺序有意义：逐用例明细按它输出，指标按它聚合，
	// 于是「同一份数据 + 同一个召回器 → 同一份报告」这条可复现承诺成立。
	Cases []Case
}
